# ------------------------------------------------------------
# Author: Yi Liao (yiliao@scau.edu.cn; yiliao1022@gmail.com)
# simulate_population_SV_benchmark_shared.pl
#
# Simulate a population-scale assembly benchmark from one reference genome.
#
# Main design:
#   1) First build a population-level SV catalogue on reference coordinates.
#   2) Then assign each SV to one or more query genomes.
#   3) Write one mutated FASTA per query and one population truth VCF.
#
# This version explicitly supports shared SVs: one VCF record can have multiple
# samples genotyped as 1|1 or 1/1 depending on --gt_sep.
# It also supports SV-type-specific length ranges, especially long inversions
# through --inv_min/--inv_max, and symbolic <INV> VCF alleles for large events.
# This version also simulates population-level SNPs and 1-50 bp small InDels
# together with large DEL/INS/INV events.
# ------------------------------------------------------------

my %opt = (
    outdir          => 'SVsim_shared_out',
    prefix          => 'SIM',
    n               => 10,
    seed            => 12345,

    # These are population-level SV locus counts, not per-sample counts.
    del             => 100,
    ins             => 100,
    inv             => 50,

    # Small variants are also population-level locus counts.
    # Defaults are 0 to keep the old SV-only behavior unless requested.
    snp             => 0,
    small_indel     => 0,   # optional total count; split approximately 1:1 into SDEL/SINS
    small_del       => 0,
    small_ins       => 0,

    min             => 50,
    max             => 10000,
    del_min         => undef,
    del_max         => undef,
    ins_min         => undef,
    ins_max         => undef,
    inv_min         => undef,
    inv_max         => undef,
    small_min       => 1,
    small_max       => 50,

    # Fraction of insertion events generated by local tandem duplication.
    td_rate         => 0.10,
    copy_rev_rate   => 0.00,

    # Population sharing model.
    shared_rate     => 0.70,   # fraction of SV loci carried by >=2 samples when n >= 2
    af_min          => 0.05,   # used for shared SVs
    af_max          => 0.50,   # used for shared SVs
    gt_sep          => '|',    # output 1|1 and 0|0 by default; use / for 1/1

    max_n_frac      => 0.50,
    buffer          => 0,
    max_try         => 100000,
    length_mode     => 'log',
    write_per_sample_vcf => 1,

    # For long inversions, symbolic VCF alleles avoid enormous REF/ALT fields.
    # Use --no-symbolic_inv to output exact REF and reverse-complement ALT.
    symbolic_inv    => 1,

    help            => 0,
);

GetOptions(
    'ref=s'                 => \$opt{ref},
    'outdir=s'              => \$opt{outdir},
    'prefix=s'              => \$opt{prefix},
    'n=i'                   => \$opt{n},
    'seed=i'                => \$opt{seed},

    'del=i'                 => \$opt{del},
    'ins=i'                 => \$opt{ins},
    'inv=i'                 => \$opt{inv},
    'snp=i'                 => \$opt{snp},
    'small_indel|sindel=i'  => \$opt{small_indel},
    'small_del|sdel=i'      => \$opt{small_del},
    'small_ins|sins=i'      => \$opt{small_ins},
    'min=i'                 => \$opt{min},
    'max=i'                 => \$opt{max},
    'del_min=i'             => \$opt{del_min},
    'del_max=i'             => \$opt{del_max},
    'ins_min=i'             => \$opt{ins_min},
    'ins_max=i'             => \$opt{ins_max},
    'inv_min=i'             => \$opt{inv_min},
    'inv_max=i'             => \$opt{inv_max},
    'small_min=i'           => \$opt{small_min},
    'small_max=i'           => \$opt{small_max},

    'td_rate=f'             => \$opt{td_rate},
    'copy_rev_rate=f'       => \$opt{copy_rev_rate},
    'shared_rate=f'         => \$opt{shared_rate},
    'af_min=f'              => \$opt{af_min},
    'af_max=f'              => \$opt{af_max},
    'gt_sep=s'              => \$opt{gt_sep},

    'max_n_frac=f'          => \$opt{max_n_frac},
    'buffer=i'              => \$opt{buffer},
    'max_try=i'             => \$opt{max_try},
    'length_mode=s'         => \$opt{length_mode},
    'write_per_sample_vcf!' => \$opt{write_per_sample_vcf},
    'symbolic_inv!'         => \$opt{symbolic_inv},
    'help|h'                => \$opt{help},
) or die usage();

if ($opt{help} || !$opt{ref}) {
    print usage();
    exit($opt{help} ? 0 : 1);
}

validate_options(\%opt);

srand($opt{seed});
make_path($opt{outdir});
make_path("$opt{outdir}/genomes");
make_path("$opt{outdir}/events");
make_path("$opt{outdir}/vcf") if $opt{write_per_sample_vcf};

my $log_file = "$opt{outdir}/simulation.log";
open(my $LOG, '>', $log_file) or die "ERROR: cannot write $log_file: $!\n";
logmsg($LOG, "Reference: $opt{ref}");
logmsg($LOG, "Output directory: $opt{outdir}");
logmsg($LOG, "Samples: $opt{n}");
logmsg($LOG, "Population large SV loci: DEL=$opt{del}; INS=$opt{ins}; INV=$opt{inv}");
logmsg($LOG, "Population small-variant loci: SNP=$opt{snp}; SDEL=$opt{small_del}; SINS=$opt{small_ins}; small length=$opt{small_min}-$opt{small_max} bp");
logmsg($LOG, "Length ranges: DEL=$opt{del_min}-$opt{del_max}; INS=$opt{ins_min}-$opt{ins_max}; INV=$opt{inv_min}-$opt{inv_max}");
logmsg($LOG, "VCF inversion representation: " . ($opt{symbolic_inv} ? 'symbolic <INV>' : 'exact REF/reverse-complement ALT'));
logmsg($LOG, "INS tandem-duplication rate: $opt{td_rate}");
logmsg($LOG, "Shared SV locus rate: $opt{shared_rate}; AF range for shared loci: $opt{af_min}-$opt{af_max}");
logmsg($LOG, "VCF GT separator: $opt{gt_sep}");

logmsg($LOG, "Reading reference FASTA into memory ...");
my ($seqs, $chroms) = read_fasta($opt{ref});
my %chr_len = map { $_ => length($seqs->{$_}) } @$chroms;
my $genome_len = 0;
$genome_len += $chr_len{$_} for @$chroms;
logmsg($LOG, "Loaded " . scalar(@$chroms) . " sequences; total length = $genome_len bp");

my @samples = map { sprintf("%s%03d", $opt{prefix}, $_) } 1 .. $opt{n};

logmsg($LOG, "Building population-level SV catalogue ...");
my @catalog = simulate_population_catalog($seqs, $chroms, \%chr_len, $genome_len, \%opt, $LOG);
assign_carriers_to_catalog(\@catalog, \@samples, \%opt);

my $catalog_tsv = "$opt{outdir}/$opt{prefix}.catalog.tsv";
write_catalog_tsv($catalog_tsv, \@catalog);
logmsg($LOG, "Catalog written: $catalog_tsv");

my %sample_events;
for my $sample (@samples) {
    my @evs = grep { $_->{carriers}{$sample} } @catalog;
    @evs = sort { cmp_event($a, $b) } @evs;
    $sample_events{$sample} = \@evs;

    my $event_tsv = "$opt{outdir}/events/$sample.events.tsv";
    write_event_tsv($event_tsv, $sample, \@evs);

    my $fa = "$opt{outdir}/genomes/$sample";
    write_mutated_fasta($fa, $sample, $seqs, $chroms, \@evs);

    if ($opt{write_per_sample_vcf}) {
        my $vcf = "$opt{outdir}/vcf/$sample.truth.vcf";
        write_vcf($vcf, \@evs, [$sample], $chroms, \%chr_len, $seqs, \%opt);
    }

    my %count;
    $count{$_->{type}}++ for @evs;
    my $count_msg = join(', ', map { $_ . '=' . ($count{$_}//0) } qw/SNP SDEL SINS DEL INS INV/);
    logmsg($LOG, "$sample done: carried $count_msg");
}

my $pop_vcf = "$opt{outdir}/$opt{prefix}.population.truth.vcf";
logmsg($LOG, "Writing population VCF: $pop_vcf");
write_vcf($pop_vcf, \@catalog, \@samples, $chroms, \%chr_len, $seqs, \%opt);

my $manifest = "$opt{outdir}/manifest.tsv";
open(my $MAN, '>', $manifest) or die "ERROR: cannot write $manifest: $!\n";
print $MAN join("\t", qw/SAMPLE FASTA EVENTS PER_SAMPLE_VCF/), "\n";
for my $sample (@samples) {
    my $vcf = $opt{write_per_sample_vcf} ? "$opt{outdir}/vcf/$sample.truth.vcf" : "NA";
    print $MAN join("\t", $sample, "$opt{outdir}/genomes/$sample", "$opt{outdir}/events/$sample.events.tsv", $vcf), "\n";
}
close $MAN;

logmsg($LOG, "Finished.");
logmsg($LOG, "Population VCF: $pop_vcf");
logmsg($LOG, "Manifest: $manifest");
close $LOG;

print STDERR "Done.\n";
print STDERR "Population VCF: $pop_vcf\n";
print STDERR "Catalog: $catalog_tsv\n";
print STDERR "Simulated genomes: $opt{outdir}/genomes/\n";
print STDERR "Event tables: $opt{outdir}/events/\n";
print STDERR "Log: $log_file\n";

# ------------------------------------------------------------
# Validation
# ------------------------------------------------------------
sub validate_options {
    my ($opt) = @_;
    for my $k (qw/del ins inv snp small_indel small_del small_ins/) {
        die "ERROR: --$k must be >= 0\n" if $opt->{$k} < 0;
    }
    if ($opt->{small_indel} > 0) {
        my $d = int($opt->{small_indel} / 2);
        my $i = $opt->{small_indel} - $d;
        $opt->{small_del} += $d;
        $opt->{small_ins} += $i;
    }
    die "ERROR: --n must be > 0\n" if $opt->{n} <= 0;
    die "ERROR: --td_rate must be between 0 and 1\n" if $opt->{td_rate} < 0 || $opt->{td_rate} > 1;
    die "ERROR: --copy_rev_rate must be between 0 and 1\n" if $opt->{copy_rev_rate} < 0 || $opt->{copy_rev_rate} > 1;
    die "ERROR: --shared_rate must be between 0 and 1\n" if $opt->{shared_rate} < 0 || $opt->{shared_rate} > 1;
    die "ERROR: --af_min and --af_max must be between 0 and 1\n" if $opt->{af_min} < 0 || $opt->{af_min} > 1 || $opt->{af_max} < 0 || $opt->{af_max} > 1;
    die "ERROR: --af_min cannot be larger than --af_max\n" if $opt->{af_min} > $opt->{af_max};
    die "ERROR: --gt_sep must be either '|' or '/'\n" unless $opt->{gt_sep} eq '|' || $opt->{gt_sep} eq '/';
    die "ERROR: --length_mode must be uniform or log\n" unless $opt->{length_mode} eq 'uniform' || $opt->{length_mode} eq 'log';

    $opt->{del_min} //= $opt->{min};
    $opt->{del_max} //= $opt->{max};
    $opt->{ins_min} //= $opt->{min};
    $opt->{ins_max} //= $opt->{max};
    $opt->{inv_min} //= $opt->{min};
    $opt->{inv_max} //= $opt->{max};

    die "ERROR: --small_min and --small_max must be positive\n" if $opt->{small_min} <= 0 || $opt->{small_max} <= 0;
    die "ERROR: --small_min cannot be larger than --small_max\n" if $opt->{small_min} > $opt->{small_max};

    for my $pair ([qw/del_min del_max/], [qw/ins_min ins_max/], [qw/inv_min inv_max/]) {
        my ($a, $b) = @$pair;
        die "ERROR: --$a and --$b must be positive\n" if $opt->{$a} <= 0 || $opt->{$b} <= 0;
        die "ERROR: --$a cannot be larger than --$b\n" if $opt->{$a} > $opt->{$b};
    }
}

# ------------------------------------------------------------
# Population catalogue simulation
# ------------------------------------------------------------
sub simulate_population_catalog {
    my ($seqs, $chroms, $chr_len, $genome_len, $opt, $LOG) = @_;

    my @jobs = (
        (('SNP')  x $opt->{snp}),
        (('SDEL') x $opt->{small_del}),
        (('SINS') x $opt->{small_ins}),
        (('DEL')  x $opt->{del}),
        (('INS')  x $opt->{ins}),
        (('INV')  x $opt->{inv}),
    );
    @jobs = shuffle(@jobs);

    my @events;
    my %occupied;  # global non-overlap on target reference coordinates
    my %failed;

    JOB:
    for my $type (@jobs) {
        my $ok;
        for my $try (1 .. $opt->{max_try}) {
            my $ev;
            if ($type eq 'SNP') {
                $ev = propose_snp($seqs, $chroms, $chr_len, $genome_len, $opt, \%occupied);
            } elsif ($type eq 'SDEL') {
                $ev = propose_small_del($seqs, $chroms, $chr_len, $genome_len, $opt, \%occupied);
            } elsif ($type eq 'SINS') {
                $ev = propose_small_ins($seqs, $chroms, $chr_len, $genome_len, $opt, \%occupied);
            } elsif ($type eq 'DEL') {
                $ev = propose_del($seqs, $chroms, $chr_len, $genome_len, $opt, \%occupied);
            } elsif ($type eq 'INS') {
                $ev = propose_ins($seqs, $chroms, $chr_len, $genome_len, $opt, \%occupied);
            } elsif ($type eq 'INV') {
                $ev = propose_inv($seqs, $chroms, $chr_len, $genome_len, $opt, \%occupied);
            } else {
                die "Internal error: unknown type $type\n";
            }

            if ($ev) {
                push @events, $ev;
                my ($s, $e) = target_interval_for_occupancy($ev);
                push @{ $occupied{$ev->{chr}} }, [$s, $e];
                $ok = 1;
                last;
            }
        }
        if (!$ok) {
            $failed{$type}++;
        }
    }

    if (%failed) {
        for my $type (sort keys %failed) {
            logmsg($LOG, "WARNING: failed to place $failed{$type} population-level $type events after max_try=$opt->{max_try}. Try fewer events, smaller max length, higher max_n_frac, or lower buffer.");
        }
    }

    @events = sort { cmp_event($a, $b) } @events;
    my %idx_by_type;
    for my $ev (@events) {
        $idx_by_type{$ev->{type}}++;
        $ev->{id} = sprintf("VAR_%s_%06d", $ev->{type}, $idx_by_type{$ev->{type}});
    }
    return @events;
}

sub assign_carriers_to_catalog {
    my ($events, $samples, $opt) = @_;
    my $n = scalar(@$samples);

    for my $ev (@$events) {
        my $k;
        if ($n == 1) {
            $k = 1;
        } elsif (rand() < $opt->{shared_rate}) {
            my $af = $opt->{af_min} + rand() * ($opt->{af_max} - $opt->{af_min});
            $k = int($af * $n + 0.5);
            $k = 2 if $k < 2;
            $k = $n if $k > $n;
        } else {
            $k = 1;
        }

        my @picked = (shuffle(@$samples))[0 .. $k - 1];
        $ev->{carriers} = { map { $_ => 1 } @picked };
        $ev->{carrier_count} = $k;
        $ev->{af} = $k / $n;
    }
}

sub propose_snp {
    my ($seqs, $chroms, $chr_len, $genome_len, $opt, $occupied) = @_;
    my $chr = weighted_chr($chroms, $chr_len, $genome_len);
    return undef if $chr_len->{$chr} < 1;

    my $pos = 1 + int(rand($chr_len->{$chr}));
    return undef if interval_occupied($occupied, $chr, $pos, $pos, $opt->{buffer});

    my $ref = uc substr($seqs->{$chr}, $pos - 1, 1);
    return undef unless $ref =~ /^[ACGT]$/;
    my $alt = random_base_except($ref);

    return {
        type   => 'SNP',
        chr    => $chr,
        start  => $pos,
        end    => $pos,
        pos    => $pos,
        len    => 1,
        method => 'RANDOM_BASE_SUBSTITUTION',
        src    => '.',
        seq    => '',
        refseq => $ref,
        altseq => $alt,
    };
}

sub propose_small_del {
    my ($seqs, $chroms, $chr_len, $genome_len, $opt, $occupied) = @_;
    my $chr = weighted_chr($chroms, $chr_len, $genome_len);
    my $len = random_len($opt->{small_min}, $opt->{small_max}, $opt->{length_mode});
    return undef if $chr_len->{$chr} <= $len + 1;

    # start >= 2 to provide a left anchor base in the VCF.
    my $start = 2 + int(rand($chr_len->{$chr} - $len));
    my $end   = $start + $len - 1;
    return undef if interval_occupied($occupied, $chr, $start, $end, $opt->{buffer});

    my $ref = substr($seqs->{$chr}, $start - 1, $len);
    return undef if n_fraction($ref) > $opt->{max_n_frac};

    return {
        type   => 'SDEL',
        chr    => $chr,
        start  => $start,
        end    => $end,
        pos    => $start - 1,
        len    => $len,
        method => 'DELETE_REF_INTERVAL_SMALL',
        src    => '.',
        seq    => '',
        refseq => $ref,
        altseq => '',
    };
}

sub propose_small_ins {
    my ($seqs, $chroms, $chr_len, $genome_len, $opt, $occupied) = @_;
    my $chr = weighted_chr($chroms, $chr_len, $genome_len);
    my $len = random_len($opt->{small_min}, $opt->{small_max}, $opt->{length_mode});
    return undef if $chr_len->{$chr} < 1;

    # Insertion is placed after this reference base.
    my $pos = 1 + int(rand($chr_len->{$chr}));
    return undef if interval_occupied($occupied, $chr, $pos, $pos, $opt->{buffer});

    my $insseq = random_dna($len);
    return {
        type   => 'SINS',
        chr    => $chr,
        pos    => $pos,
        start  => $pos,
        end    => $pos,
        len    => $len,
        method => 'RANDOM_SMALL_INSERTION',
        src    => '.',
        seq    => $insseq,
        refseq => '',
        altseq => $insseq,
    };
}

