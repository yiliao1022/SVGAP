# VCF creation
# ------------------------------------------------------------
sub event_to_vcf_variant {
    my ($ev, $seqs, $opt) = @_;
    my ($chr, $type) = ($ev->{chr}, $ev->{type});
    my ($pos, $ref, $alt, $end, $svlen, $svtype);

    if ($type eq 'SNP') {
        $pos = $ev->{pos};
        $ref = $ev->{refseq};
        $alt = $ev->{altseq};
        $end = $ev->{pos};
        $svlen = 1;
        $svtype = 'SNP';
    } elsif ($type eq 'DEL' || $type eq 'SDEL') {
        # VCF left-anchor: deletion of reference interval [start, end]
        # is represented at POS=start-1.
        my $anchor_pos = $ev->{start} - 1;
        my $anchor = substr($seqs->{$chr}, $anchor_pos - 1, 1);
        my $deleted = substr($seqs->{$chr}, $ev->{start} - 1, $ev->{len});
        $pos = $anchor_pos;
        $ref = $anchor . $deleted;
        $alt = $anchor;
        $end = $ev->{end};
        $svlen = -$ev->{len};
        $svtype = 'DEL';
    } elsif ($type eq 'INS' || $type eq 'SINS') {
        my $anchor = substr($seqs->{$chr}, $ev->{pos} - 1, 1);
        $pos = $ev->{pos};
        $ref = $anchor;
        $alt = $anchor . $ev->{seq};
        $end = $ev->{pos};
        $svlen = $ev->{len};
        $svtype = 'INS';
    } elsif ($type eq 'INV') {
        $pos = $ev->{start};
        $end = $ev->{end};
        $svlen = $ev->{len};
        $svtype = 'INV';
        if ($opt->{symbolic_inv}) {
            # Long inversions can be hundreds of kb to Mb.  A symbolic allele
            # keeps the truth VCF compact while END/SVLEN preserve coordinates.
            $ref = substr($seqs->{$chr}, $ev->{start} - 1, 1);
            $alt = '<INV>';
        } else {
            my $seg = substr($seqs->{$chr}, $ev->{start} - 1, $ev->{len});
            $ref = $seg;
            $alt = revcomp($seg);
        }
    } else {
        die "Internal error: unknown event type $type\n";
    }

    return {
        chr    => $chr,
        pos    => $pos,
        type   => $type,
        svtype => $svtype,
        end    => $end,
        svlen  => $svlen,
        ref    => $ref,
        alt    => $alt,
        method => $ev->{method} // '.',
        src    => $ev->{src} // '.',
        id     => $ev->{id} // '.',
        carriers => $ev->{carriers} || {},
    };
}

sub write_vcf {
    my ($out, $events, $samples, $chroms, $chr_len, $seqs, $opt) = @_;
    open(my $VCF, '>', $out) or die "ERROR: cannot write $out: $!\n";

    print $VCF "##fileformat=VCFv4.2\n";
    print $VCF "##source=simulate_population_SV_benchmark_shared.pl\n";
    print $VCF "##simulation_note=Variant loci are generated once at the population level and then assigned to samples; therefore one VCF record can be carried by multiple samples.\n";
    print $VCF "##ALT=<ID=INV,Description=\"Inversion\">\n" if $opt->{symbolic_inv};
    for my $chr (@$chroms) {
        print $VCF "##contig=<ID=$chr,length=$chr_len->{$chr}>\n";
    }
    print $VCF "##INFO=<ID=SVTYPE,Number=1,Type=String,Description=\"Variant/SV class: SNP, DEL, INS or INV\">\n";
    print $VCF "##INFO=<ID=VARTYPE,Number=1,Type=String,Description=\"Detailed simulated variant type: SNP, SDEL, SINS, DEL, INS or INV\">\n";
    print $VCF "##INFO=<ID=END,Number=1,Type=Integer,Description=\"End position on the reference\">\n";
    print $VCF "##INFO=<ID=SVLEN,Number=1,Type=Integer,Description=\"SV length; negative for deletions\">\n";
    print $VCF "##INFO=<ID=METHOD,Number=1,Type=String,Description=\"How the SV was simulated\">\n";
    print $VCF "##INFO=<ID=SRC,Number=1,Type=String,Description=\"Source interval of inserted copied sequence, if applicable\">\n";
    print $VCF "##INFO=<ID=NCARRIERS,Number=1,Type=Integer,Description=\"Number of samples carrying this simulated SV\">\n";
    print $VCF "##INFO=<ID=AF,Number=1,Type=Float,Description=\"Carrier frequency among simulated assemblies\">\n";
    print $VCF "##INFO=<ID=CARRIERS,Number=.,Type=String,Description=\"Samples carrying this simulated SV\">\n";
    print $VCF "##FORMAT=<ID=GT,Number=1,Type=String,Description=\"Genotype: 1$opt->{gt_sep}1 means the simulated assembly carries this SV; 0$opt->{gt_sep}0 means reference allele\">\n";
    print $VCF join("\t", '#CHROM', 'POS', 'ID', 'REF', 'ALT', 'QUAL', 'FILTER', 'INFO', 'FORMAT', @$samples), "\n";

    my %chr_order;
    my $rank = 0;
    $chr_order{$_} = ++$rank for @$chroms;

    my @vars = sort {
        ($chr_order{$a->{chr}} // 1e12) <=> ($chr_order{$b->{chr}} // 1e12)
        || $a->{pos} <=> $b->{pos}
        || $a->{end} <=> $b->{end}
        || $a->{type} cmp $b->{type}
    } map { event_to_vcf_variant($_, $seqs, $opt) } @$events;

    for my $v (@vars) {
        my @carriers = sort keys %{ $v->{carriers} || {} };
        my $ncar = scalar(@carriers);
        my $af = @$samples ? $ncar / scalar(@$samples) : 0;
        my $carrier_string = @carriers ? join(',', @carriers) : '.';
        my $info = join(';',
            "SVTYPE=$v->{svtype}",
            "VARTYPE=$v->{type}",
            "END=$v->{end}",
            "SVLEN=$v->{svlen}",
            "METHOD=" . vcf_clean($v->{method}),
            "SRC=" . vcf_clean($v->{src}),
            "NCARRIERS=$ncar",
            "AF=" . sprintf("%.6f", $af),
            "CARRIERS=" . vcf_clean($carrier_string),
        );
        my @gt = map { ($v->{carriers}{$_} ? "1$opt->{gt_sep}1" : "0$opt->{gt_sep}0") } @$samples;
        print $VCF join("\t", $v->{chr}, $v->{pos}, $v->{id}, uc($v->{ref}), uc($v->{alt}), '.', 'PASS', $info, 'GT', @gt), "\n";
    }
    close $VCF;
}

# ------------------------------------------------------------
# Utility functions
# ------------------------------------------------------------
sub read_fasta {
    my ($file) = @_;
    open(my $IN, '<', $file) or die "ERROR: cannot read $file: $!\n";
    my (%seq, @order, $id);
    while (my $line = <$IN>) {
        chomp $line;
        next if $line =~ /^\s*$/;
        if ($line =~ /^>(\S+)/) {
            $id = $1;
            die "ERROR: duplicated FASTA sequence ID: $id\n" if exists $seq{$id};
            $seq{$id} = '';
            push @order, $id;
        } else {
            die "ERROR: sequence line appears before FASTA header\n" unless defined $id;
            $line =~ s/\s+//g;
            $seq{$id} .= uc($line);
        }
    }
    close $IN;
    die "ERROR: no sequences found in $file\n" unless @order;
    return (\%seq, \@order);
}

sub weighted_chr {
    my ($chroms, $chr_len, $genome_len) = @_;
    my $x = rand($genome_len);
    my $acc = 0;
    for my $chr (@$chroms) {
        $acc += $chr_len->{$chr};
        return $chr if $x < $acc;
    }
    return $chroms->[-1];
}

sub random_len {
    my ($min, $max, $mode) = @_;
    return $min if $min == $max;
    if ($mode eq 'uniform') {
        return $min + int(rand($max - $min + 1));
    }
    # Log-uniform gives more short SVs while still sampling long events.
    my $log_min = log($min);
    my $log_max = log($max);
    my $v = exp($log_min + rand() * ($log_max - $log_min));
    my $len = int($v + 0.5);
    $len = $min if $len < $min;
    $len = $max if $len > $max;
    return $len;
}

sub random_base_except {
    my ($ref) = @_;
    my @bases = grep { $_ ne uc($ref) } qw/A C G T/;
    return $bases[int(rand(@bases))];
}

sub random_dna {
    my ($len) = @_;
    my @bases = qw/A C G T/;
    my $seq = '';
    for (1 .. $len) {
        $seq .= $bases[int(rand(@bases))];
    }
    return $seq;
}

sub event_svlen {
    my ($ev) = @_;
    return -$ev->{len} if $ev->{type} eq 'DEL' || $ev->{type} eq 'SDEL';
    return $ev->{len};
}

sub event_ref_alt_seq {
    my ($ev) = @_;
    my $ref = defined $ev->{refseq} ? $ev->{refseq} : '.';
    my $alt = defined $ev->{altseq} ? $ev->{altseq} : '.';
    $ref = '.' if $ref eq '';
    $alt = '.' if $alt eq '';
    return ($ref, $alt);
}

sub target_interval_for_occupancy {
    my ($ev) = @_;
    if ($ev->{type} eq 'INS' || $ev->{type} eq 'SINS' || $ev->{type} eq 'SNP') {
        return ($ev->{pos}, $ev->{pos});
    }
    return ($ev->{start}, $ev->{end});
}

sub interval_occupied {
    my ($occupied, $chr, $s, $e, $buffer) = @_;
    $buffer //= 0;
    my $qs = $s - $buffer;
    my $qe = $e + $buffer;
    for my $int (@{ $occupied->{$chr} || [] }) {
        my ($a, $b) = @$int;
        return 1 if $qs <= $b && $qe >= $a;
    }
    return 0;
}

sub n_fraction {
    my ($seq) = @_;
    return 1 if !defined($seq) || $seq eq '';
    my $n = ($seq =~ tr/Nn//);
    return $n / length($seq);
}

sub revcomp {
    my ($s) = @_;
    $s = reverse($s);
    $s =~ tr/ACGTRYSWKMBDHVNacgtryswkmbdhvn/TGCAYRSWMKVHDBNtgcayrswmkvhdbn/;
    return $s;
}

sub cmp_event {
    my ($a, $b) = @_;
    return ($a->{chr} cmp $b->{chr})
        || (($a->{pos} // $a->{start}) <=> ($b->{pos} // $b->{start}))
        || (($a->{start} // $a->{pos}) <=> ($b->{start} // $b->{pos}))
        || (($a->{end} // $a->{pos}) <=> ($b->{end} // $b->{pos}))
        || ($a->{type} cmp $b->{type});
}

sub print_wrapped {
    my ($fh, $seq, $width) = @_;
    $width ||= 80;
    for (my $i = 0; $i < length($seq); $i += $width) {
        print $fh substr($seq, $i, $width), "\n";
    }
}

sub simulated_chr_id {
    my ($sample, $ref_chr) = @_;
    my $suffix = $ref_chr;

    # Common case: S184.Chr01 -> Chr01, CA59.Chr12 -> Chr12.
    # If no Chr-like suffix exists, fall back to the text after the last dot;
    # if there is no dot, use the full original reference sequence ID.
    if ($suffix =~ /((?:Chr|chr|CHR)\d+\S*)$/) {
        $suffix = $1;
    } elsif ($suffix =~ /^.+\.(.+)$/) {
        $suffix = $1;
    }

    return "$sample.$suffix";
}


sub vcf_clean {
    my ($s) = @_;
    $s = '.' if !defined($s) || $s eq '';
    $s =~ s/[;\t\s]+/_/g;
    return $s;
}

sub logmsg {
    my ($fh, $msg) = @_;
    my $t = scalar(localtime());
    print $fh "[$t] $msg\n";
}

