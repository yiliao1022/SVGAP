}

sub propose_inv {
    my ($seqs, $chroms, $chr_len, $genome_len, $opt, $occupied) = @_;
    my $chr = weighted_chr($chroms, $chr_len, $genome_len);
    my $len = random_len($opt->{inv_min}, $opt->{inv_max}, $opt->{length_mode});
    return undef if $chr_len->{$chr} < $len;

    my $start = 1 + int(rand($chr_len->{$chr} - $len + 1));
    my $end   = $start + $len - 1;
    return undef if interval_occupied($occupied, $chr, $start, $end, $opt->{buffer});

    my $ref = substr($seqs->{$chr}, $start - 1, $len);
    return undef if n_fraction($ref) > $opt->{max_n_frac};

    return {
        type   => 'INV',
        chr    => $chr,
        start  => $start,
        end    => $end,
        pos    => $start,
        len    => $len,
        method => 'INVERT_REF_INTERVAL',
        src    => '.',
        seq    => '',
        refseq => '.',
        altseq => '.',
    };
}

sub propose_ins {
    my ($seqs, $chroms, $chr_len, $genome_len, $opt, $occupied) = @_;
    my $chr = weighted_chr($chroms, $chr_len, $genome_len);
    my $len = random_len($opt->{ins_min}, $opt->{ins_max}, $opt->{length_mode});
    return undef if $chr_len->{$chr} < 1;

    # Insertion is placed after this reference base.
    my $pos = 1 + int(rand($chr_len->{$chr}));
    return undef if interval_occupied($occupied, $chr, $pos, $pos, $opt->{buffer});

    my ($insseq, $method, $src) = ('', '', '');

    if (rand() < $opt->{td_rate}) {
        my @side;
        push @side, 'LEFT'  if $pos - $len + 1 >= 1;
        push @side, 'RIGHT' if $pos + $len <= $chr_len->{$chr};
        return undef unless @side;

        my $side = $side[int(rand(@side))];
        my ($src_start, $src_end);
        if ($side eq 'LEFT') {
            $src_start = $pos - $len + 1;
            $src_end   = $pos;
        } else {
            $src_start = $pos + 1;
            $src_end   = $pos + $len;
        }
        $insseq = substr($seqs->{$chr}, $src_start - 1, $len);
        return undef if n_fraction($insseq) > $opt->{max_n_frac};

        $method = "TANDEM_DUPLICATION_$side";
        $src = "$chr:$src_start-$src_end:+";
    } else {
        my $src_chr = weighted_chr($chroms, $chr_len, $genome_len);
        return undef if $chr_len->{$src_chr} < $len;
        my $src_start = 1 + int(rand($chr_len->{$src_chr} - $len + 1));
        my $src_end   = $src_start + $len - 1;

        # For non-tandem copied insertions, avoid copying the immediate local region.
        if ($src_chr eq $chr) {
            my $local_start = $pos - $len;
            my $local_end   = $pos + $len;
            return undef if $src_start <= $local_end && $src_end >= $local_start;
        }

        $insseq = substr($seqs->{$src_chr}, $src_start - 1, $len);
        return undef if n_fraction($insseq) > $opt->{max_n_frac};

        my $strand = '+';
        if (rand() < $opt->{copy_rev_rate}) {
            $insseq = revcomp($insseq);
            $strand = '-';
        }
        $method = 'DISPERSED_COPY_INSERTION';
        $src = "$src_chr:$src_start-$src_end:$strand";
    }

    return {
        type   => 'INS',
        chr    => $chr,
        pos    => $pos,
        start  => $pos,
        end    => $pos,
        len    => length($insseq),
        method => $method,
        src    => $src,
        seq    => $insseq,
        refseq => '',
        altseq => $insseq,
    };
}

# ------------------------------------------------------------
# Output mutated FASTA
# ------------------------------------------------------------
sub write_mutated_fasta {
    my ($out, $sample, $seqs, $chroms, $events) = @_;
    open(my $OUT, '>', $out) or die "ERROR: cannot write $out: $!\n";

    my %by_chr;
    push @{ $by_chr{$_->{chr}} }, $_ for @$events;

    for my $chr (@$chroms) {
        my $ref = $seqs->{$chr};
        my $ref_len = length($ref);
        my $new = '';
        my $cursor = 1;

        my @evs = sort { cmp_event($a, $b) } @{ $by_chr{$chr} || [] };
        for my $ev (@evs) {
            if ($ev->{type} eq 'INS' || $ev->{type} eq 'SINS') {
                my $pos = $ev->{pos};
                if ($pos >= $cursor) {
                    $new .= substr($ref, $cursor - 1, $pos - $cursor + 1);
                    $cursor = $pos + 1;
                }
                $new .= $ev->{seq};
            } elsif ($ev->{type} eq 'DEL' || $ev->{type} eq 'SDEL') {
                my ($s, $e) = ($ev->{start}, $ev->{end});
                next if $e < $cursor;
                $new .= substr($ref, $cursor - 1, $s - $cursor) if $s > $cursor;
                $cursor = $e + 1;
            } elsif ($ev->{type} eq 'SNP') {
                my $pos = $ev->{pos};
                next if $pos < $cursor;
                $new .= substr($ref, $cursor - 1, $pos - $cursor) if $pos > $cursor;
                $new .= $ev->{altseq};
                $cursor = $pos + 1;
            } elsif ($ev->{type} eq 'INV') {
                my ($s, $e) = ($ev->{start}, $ev->{end});
                next if $e < $cursor;
                $new .= substr($ref, $cursor - 1, $s - $cursor) if $s > $cursor;
                my $seg = substr($ref, $s - 1, $e - $s + 1);
                $new .= revcomp($seg);
                $cursor = $e + 1;
            } else {
                die "Internal error: unknown event type $ev->{type}\n";
            }
        }
        $new .= substr($ref, $cursor - 1) if $cursor <= $ref_len;

        # For downstream SVGAP convenience, the simulated assembly FASTA
        # uses clean query chromosome IDs such as SIM001.Chr01.
        # The original reference chromosome name is still preserved in the
        # event tables and truth VCF, which remain reference-coordinate based.
        my $query_chr = simulated_chr_id($sample, $chr);
        print $OUT ">$query_chr\n";
        print_wrapped($OUT, $new, 80);
    }
    close $OUT;
}

sub write_event_tsv {
    my ($out, $sample, $events) = @_;
    open(my $OUT, '>', $out) or die "ERROR: cannot write $out: $!\n";
    print $OUT join("\t", qw/SAMPLE EVENT_ID TYPE CHROM START END POS SVLEN METHOD SOURCE REF_SEQ ALT_SEQ INSERTED_SEQ_MD5 INSERTED_SEQ/), "\n";
    for my $ev (@$events) {
        my ($ref_seq, $alt_seq) = event_ref_alt_seq($ev);
        my $seq = ($ev->{type} eq 'INS' || $ev->{type} eq 'SINS') ? ($ev->{seq} || '') : '';
        my $md5 = $seq ne '' ? md5_hex($seq) : '.';
        print $OUT join("\t",
            $sample,
            $ev->{id} // '.',
            $ev->{type},
            $ev->{chr},
            $ev->{start} // '.',
            $ev->{end} // '.',
            $ev->{pos} // '.',
            event_svlen($ev),
            $ev->{method} // '.',
            $ev->{src} // '.',
            $ref_seq,
            $alt_seq,
            $md5,
            $seq eq '' ? '.' : $seq,
        ), "\n";
    }
    close $OUT;
}

sub write_catalog_tsv {
    my ($out, $events) = @_;
    open(my $OUT, '>', $out) or die "ERROR: cannot write $out: $!\n";
    print $OUT join("\t", qw/EVENT_ID TYPE CHROM START END POS SVLEN METHOD SOURCE NCARRIERS AF CARRIERS REF_SEQ ALT_SEQ INSERTED_SEQ_MD5/), "\n";
    for my $ev (sort { cmp_event($a, $b) } @$events) {
        my @carriers = sort keys %{ $ev->{carriers} || {} };
        my ($ref_seq, $alt_seq) = event_ref_alt_seq($ev);
        my $seq = ($ev->{type} eq 'INS' || $ev->{type} eq 'SINS') ? ($ev->{seq} || '') : '';
        my $md5 = $seq ne '' ? md5_hex($seq) : '.';
        print $OUT join("\t",
            $ev->{id} // '.',
            $ev->{type},
            $ev->{chr},
            $ev->{start} // '.',
            $ev->{end} // '.',
            $ev->{pos} // '.',
            event_svlen($ev),
            $ev->{method} // '.',
            $ev->{src} // '.',
            scalar(@carriers),
            sprintf("%.6f", scalar(@carriers) / ($opt{n} || 1)),
            @carriers ? join(',', @carriers) : '.',
            $ref_seq,
            $alt_seq,
            $md5,
        ), "\n";
    }
    close $OUT;
}

