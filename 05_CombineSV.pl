################################################################################
# 5_CombineSV_refactored_merge_all.pl
#
# Merge and de-redundant raw pairwise SV calls generated by PairwiseSV scripts.
# This version merges DEL, INS, CNV/tandem duplication, INV, and TRL.
#
# Important for the split indel output used by the current SVGAP workflow:
#   1) Deletions relative to the reference are taken from forward comparisons:
#        <refname>.<query>.rawSV/*.del.sort
#   2) Insertions relative to the reference are taken from reciprocal comparisons:
#        <query>.<refname>.rawSV/*.del.sort
#      because a deletion in query-as-target coordinates corresponds to an
#      insertion relative to the original reference.
#   3) *.ins.sort files from both directions are written as reference/support
#      files only and are not used in the main merged DEL/INS catalog by default.
#   4) Legacy *.indel.sort input is still supported when split *.del.sort files
#      are not found.
#
# Coordinates remain 0-based half-open, consistent with BED/rawSV outputs.
################################################################################

my %OPT = (
    outdir        => 'CombinedSV',
    ins_tol       => 13,
    del_ov        => 0.90,
    len_ratio     => 0.05,
    candidate     => 50,
    min_large_len => 50,
    max_indel_len => 100000,

    # Current SVGAP PairwiseSV splits the old *.indel.sort into *.del.sort
    # and *.ins.sort.  Use *.del.sort as the main source for both DEL and INS
    # catalogs, with reciprocal orientation for INS.
    legacy_indel  => 1,
    write_ins_reference => 1,

    # Merge parameters for other SV classes
    cnv_ov        => 0.50,
    cnv_len_ratio => 0.50,
    cnv_bp_tol    => 50000,
    inv_ov        => 0.50,
    inv_len_ratio => 0.50,
    inv_bp_tol    => 50000,
    trl_ov        => 0.30,
    trl_len_ratio => 1.00,
    trl_bp_tol    => 100000,
    trl_require_qchr => 0,

    sort_mem      => '10G',
    sort_threads  => 1,
    sort_bin      => 'sort',
    keep_temp     => 0,
    verbose       => 1,
);

my $help = 0;
GetOptions(
    'sv|svdir|pairsv=s'     => \$OPT{svdir},
    'refname=s'             => \$OPT{refname},
    'outdir=s'              => \$OPT{outdir},

    'ins_tol=f'             => \$OPT{ins_tol},
    'del_ov=f'              => \$OPT{del_ov},
    'len_ratio=f'           => \$OPT{len_ratio},
    'cant|candidate=i'      => \$OPT{candidate},
    'min_large_len=i'       => \$OPT{min_large_len},
    'max_indel_len=i'       => \$OPT{max_indel_len},
    'legacy_indel!'         => \$OPT{legacy_indel},
    'write_ins_reference!'  => \$OPT{write_ins_reference},

    'cnv_ov=f'              => \$OPT{cnv_ov},
    'cnv_len_ratio=f'       => \$OPT{cnv_len_ratio},
    'cnv_bp_tol=i'          => \$OPT{cnv_bp_tol},
    'inv_ov=f'              => \$OPT{inv_ov},
    'inv_len_ratio=f'       => \$OPT{inv_len_ratio},
    'inv_bp_tol=i'          => \$OPT{inv_bp_tol},
    'trl_ov=f'              => \$OPT{trl_ov},
    'trl_len_ratio=f'       => \$OPT{trl_len_ratio},
    'trl_bp_tol=i'          => \$OPT{trl_bp_tol},
    'trl_require_qchr!'     => \$OPT{trl_require_qchr},

    'sort_mem=s'            => \$OPT{sort_mem},
    'sort_threads=i'        => \$OPT{sort_threads},
    'sort_bin=s'            => \$OPT{sort_bin},
    'keep_temp!'            => \$OPT{keep_temp},
    'verbose!'              => \$OPT{verbose},
    'help|h'                => \$help,
) or die usage();

if ($help || !$OPT{svdir} || !$OPT{refname}) {
    print usage();
    exit($help ? 0 : 1);
}

$OPT{svdir} = abs_path($OPT{svdir}) || die "Cannot find --sv $OPT{svdir}\n";
$OPT{outdir} =~ s{/+$}{};
make_path($OPT{outdir}) unless -d $OPT{outdir};

my $tmpdir = tempdir('CombineSV_tmp_XXXXXX', DIR => $OPT{outdir}, CLEANUP => !$OPT{keep_temp});
log_msg("Temporary directory: $tmpdir");

my ($ref_dirs, $qry_dirs) = find_rawsv_dirs($OPT{svdir}, $OPT{refname});
log_msg("Reference-oriented rawSV directories: " . scalar(@$ref_dirs));
log_msg("Query-oriented rawSV directories: "     . scalar(@$qry_dirs));

# Current split-indel workflow:
#   forward    ref.query/*.del.sort => DEL relative to reference
#   reciprocal query.ref/*.del.sort => INS relative to reference
# Legacy workflow:
#   forward    ref.query/*.indel.sort => DEL relative to reference
#   reciprocal query.ref/*.indel.sort => INS relative to reference
my @ref_del_split_files = files_with_suffix($ref_dirs, '.del.sort');
my @qry_del_split_files = files_with_suffix($qry_dirs, '.del.sort');
my @ref_ins_split_files = files_with_suffix($ref_dirs, '.ins.sort');
my @qry_ins_split_files = files_with_suffix($qry_dirs, '.ins.sort');
my @ref_legacy_indel_files = files_with_suffix($ref_dirs, '.indel.sort');
my @qry_legacy_indel_files = files_with_suffix($qry_dirs, '.indel.sort');

my @del_indel_files = @ref_del_split_files
                    ? @ref_del_split_files
                    : ($OPT{legacy_indel} ? @ref_legacy_indel_files : ());
my @ins_indel_files = @qry_del_split_files
                    ? @qry_del_split_files
                    : ($OPT{legacy_indel} ? @qry_legacy_indel_files : ());

my @cnv_files       = files_with_suffix($qry_dirs, '.cnv.sort');
my @inv_files       = files_with_suffix($ref_dirs, '.inv.sort');
my @trl_files       = files_with_suffix($qry_dirs, '.trl.sort');

log_msg("Forward ref.query .del.sort files for reference DEL: " . scalar(@ref_del_split_files));
log_msg("Reciprocal query.ref .del.sort files for reference INS: " . scalar(@qry_del_split_files));
log_msg("Forward ref.query .ins.sort support/reference files: " . scalar(@ref_ins_split_files));
log_msg("Reciprocal query.ref .ins.sort support/reference files: " . scalar(@qry_ins_split_files));
log_msg("Legacy forward .indel.sort files: " . scalar(@ref_legacy_indel_files));
log_msg("Legacy reciprocal .indel.sort files: " . scalar(@qry_legacy_indel_files));
log_msg("Main DEL-source files used: " . scalar(@del_indel_files));
log_msg("Main INS-source files used: " . scalar(@ins_indel_files));
log_msg("CNV files: " . scalar(@cnv_files));
log_msg("INV files: " . scalar(@inv_files));
log_msg("TRL files: " . scalar(@trl_files));

warn "WARNING: no main DEL source files found. Expected ref.query/*.del.sort, or legacy ref.query/*.indel.sort.\n" unless @del_indel_files;
warn "WARNING: no main INS source files found. Expected query.ref/*.del.sort, or legacy query.ref/*.indel.sort.\n" unless @ins_indel_files;

# 1. Extract and sort raw candidate files, compatible with the original names.
my $del_large = "$OPT{outdir}/All.DELs.50bplarge.bed";
my $del_small = "$OPT{outdir}/All.DELs.50bpsmall.bed";
my $ins_large = "$OPT{outdir}/All.INTs.50bplarge.bed";
my $ins_small = "$OPT{outdir}/All.INTs.50bpsmall.bed";
my $all_cnv   = "$OPT{outdir}/All.CNVs.bed";
my $all_inv   = "$OPT{outdir}/All.INVs.bed";
my $all_trl   = "$OPT{outdir}/All.TRLs.bed";

extract_indels(\@del_indel_files, $del_large, $del_small, 'DEL');
extract_indels(\@ins_indel_files, $ins_large, $ins_small, 'INS');

# The split *.ins.sort files are not used for the main merged DEL/INS catalog.
# They are written separately for manual/reference checking because their
# interpretation depends on direction and they are less reliable for defining
# the final reference-oriented indel catalog.
if ($OPT{write_ins_reference}) {
    extract_indels_oriented(\@ref_ins_split_files,
        "$OPT{outdir}/ReferenceOnly.ref_query_INS.50bplarge.bed",
        "$OPT{outdir}/ReferenceOnly.ref_query_INS.50bpsmall.bed",
        'forward', 'REF_QUERY_INS_REFERENCE');
    extract_indels_oriented(\@qry_ins_split_files,
        "$OPT{outdir}/ReferenceOnly.query_ref_INS.50bplarge.bed",
        "$OPT{outdir}/ReferenceOnly.query_ref_INS.50bpsmall.bed",
        'reciprocal', 'QUERY_REF_INS_REFERENCE');
}
collect_and_sort(\@cnv_files, "$tmpdir/CNV.unsorted", $all_cnv, ['-k5,5', '-k6,6n', '-k7,7n']);
collect_and_sort(\@inv_files, "$tmpdir/INV.unsorted", $all_inv, ['-k1,1', '-k2,2n', '-k3,3n']);
collect_and_sort(\@trl_files, "$tmpdir/TRL.unsorted", $all_trl, ['-k4,4', '-k5,5n', '-k6,6n']);

# 2. Merge de-redundant catalogs.
merge_deletions($del_large, $OPT{del_ov}, $OPT{len_ratio}, $OPT{candidate});
merge_deletions($del_small, $OPT{del_ov}, $OPT{len_ratio}, $OPT{candidate});
merge_insertions($ins_large, $OPT{ins_tol}, $OPT{candidate});
merge_insertions($ins_small, $OPT{ins_tol}, $OPT{candidate});

# CNV is collected from reciprocal comparisons (*.<refname>.rawSV), so coordinates
# are standardized by using Sample/Sample_beg/Sample_end as the reference interval.
merge_head1_interval_sv(
    file          => $all_cnv,
    out           => "$all_cnv.combined.sorted.txt",
    svtype        => 'CNV',
    orientation   => 'reciprocal',
    min_ro        => $OPT{cnv_ov},
    len_ratio     => $OPT{cnv_len_ratio},
    bp_tol        => $OPT{cnv_bp_tol},
    candidate_num => $OPT{candidate},
    require_subtype => 0,
);

# INV is collected from reference-oriented comparisons (<refname>.*.rawSV), so
# Reference/Ref_beg/Ref_end are already reference coordinates.
merge_head1_interval_sv(
    file          => $all_inv,
    out           => "$all_inv.combined.sorted.txt",
    svtype        => 'INV',
    orientation   => 'forward',
    min_ro        => $OPT{inv_ov},
    len_ratio     => $OPT{inv_len_ratio},
    bp_tol        => $OPT{inv_bp_tol},
    candidate_num => $OPT{candidate},
    require_subtype => 0,
);

# TRL is collected from reciprocal comparisons. It has a different raw header.
merge_translocations(
    file          => $all_trl,
    out           => "$all_trl.combined.sorted.txt",
    min_ro        => $OPT{trl_ov},
    len_ratio     => $OPT{trl_len_ratio},
    bp_tol        => $OPT{trl_bp_tol},
    candidate_num => $OPT{candidate},
    require_qchr  => $OPT{trl_require_qchr},
);

log_msg("Done.");

