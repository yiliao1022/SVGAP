sub log_msg {
    return unless $OPT{verbose};
    my ($msg) = @_;
    my $time = scalar localtime();
    print STDERR "[$time] $msg\n";
}

sub find_rawsv_dirs {
    my ($svdir, $refname) = @_;
    my (@ref_dirs, @qry_dirs);

    find({
        wanted => sub {
            return unless -d $File::Find::name;
            my $base = basename($File::Find::name);
            if ($base =~ /^\Q$refname\E\..+\.rawSV$/) {
                push @ref_dirs, $File::Find::name;
            }
            if ($base =~ /^.+\.\Q$refname\E\.rawSV$/) {
                push @qry_dirs, $File::Find::name;
            }
        },
        no_chdir => 1,
    }, $svdir);

    @ref_dirs = sort @ref_dirs;
    @qry_dirs = sort @qry_dirs;
    return (\@ref_dirs, \@qry_dirs);
}

sub files_with_suffix {
    my ($dirs, $suffix) = @_;
    my @files;
    for my $dir (@$dirs) {
        opendir(my $dh, $dir) or next;
        while (my $f = readdir($dh)) {
            next unless $f =~ /\Q$suffix\E$/;
            push @files, "$dir/$f";
        }
        closedir($dh);
    }
    return sort @files;
}

sub open_read {
    my ($file) = @_;
    my $fh;
    if ($file =~ /\.gz$/) {
        open($fh, "gzip -dc '$file' |") or die "Cannot open gzipped file $file: $!\n";
    } else {
        open($fh, '<', $file) or die "Cannot open $file: $!\n";
    }
    return $fh;
}

sub extract_indels {
    my ($files, $large_out, $small_out, $mode) = @_;
    my $orientation = $mode eq 'INS' ? 'reciprocal' : 'forward';
    extract_indels_oriented($files, $large_out, $small_out, $orientation, $mode);
}

sub extract_indels_oriented {
    my ($files, $large_out, $small_out, $orientation, $label) = @_;
    my $large_tmp = "$tmpdir/$label.large.unsorted";
    my $small_tmp = "$tmpdir/$label.small.unsorted";

    open(my $LG, '>', $large_tmp) or die "Cannot write $large_tmp: $!\n";
    open(my $SM, '>', $small_tmp) or die "Cannot write $small_tmp: $!\n";

    my ($n_in, $n_large, $n_small) = (0, 0, 0);
    for my $file (@$files) {
        my $fh = open_read($file);
        while (my $line = <$fh>) {
            next if $line =~ /^\s*#/;
            chomp $line;
            next if $line =~ /^\s*$/;
            my @f = split(/\t/, $line);
            next unless @f >= 17;
            next unless defined $f[7] && $f[7] =~ /^-?\d+(?:\.\d+)?$/;
            my $len = abs($f[7]);
            next if $len <= 0;
            next if $len >= $OPT{max_indel_len};
            $n_in++;
            if ($len >= $OPT{min_large_len}) {
                print $LG "$line\n";
                $n_large++;
            } else {
                print $SM "$line\n";
                $n_small++;
            }
        }
        close $fh;
    }
    close $LG;
    close $SM;

    my @keys = $orientation eq 'reciprocal'
             ? ('-k5,5', '-k6,6n', '-k7,7n', '-k8,8n')
             : ('-k1,1', '-k2,2n', '-k3,3n', '-k8,8n');

    sort_file($large_tmp, $large_out, \@keys);
    sort_file($small_tmp, $small_out, \@keys);
    log_msg("$label candidates: orientation=$orientation, retained=$n_in, large=$n_large, small=$n_small");
}

sub collect_and_sort {
    my ($files, $tmp, $out, $keys) = @_;
    open(my $OUT, '>', $tmp) or die "Cannot write $tmp: $!\n";
    my $n = 0;
    for my $file (@$files) {
        my $fh = open_read($file);
        while (my $line = <$fh>) {
            next if $line =~ /^\s*#/;
            next if $line =~ /^\s*$/;
            print $OUT $line;
            $n++;
        }
        close $fh;
    }
    close $OUT;
    sort_file($tmp, $out, $keys);
    log_msg("Collected $n records into $out");
}

sub sort_file {
    my ($in, $out, $keys) = @_;
    open(my $test, '<', $in) or die "Cannot read $in: $!\n";
    my $has_line = <$test>;
    close $test;
    if (!defined $has_line) {
        open(my $empty, '>', $out) or die "Cannot write $out: $!\n";
        close $empty;
        return;
    }

    local $ENV{LC_ALL} = 'C';
    my @cmd = ($OPT{sort_bin}, "--buffer-size=$OPT{sort_mem}");
    push @cmd, "--parallel=$OPT{sort_threads}" if $OPT{sort_threads} && $OPT{sort_threads} > 1;
    push @cmd, @$keys, '-o', $out, $in;

    my $ret = system(@cmd);
    if ($ret != 0) {
        die "sort failed for $in. Command was: @cmd\n";
    }
}

sub merge_deletions {
    my ($file, $min_ro, $len_ratio, $candidate_num) = @_;
    my $out = "$file.combined.sorted.txt";
    open(my $IN,  '<', $file) or die "Cannot read $file: $!\n";

    my @clusters;
    my ($n_in, $n_merged) = (0, 0);
    while (my $line = <$IN>) {
        next if $line =~ /^\s*#/;
        chomp $line;
        next if $line =~ /^\s*$/;
        my @f = split(/\t/, $line);
        next unless @f >= 17;
        my $ev = parse_head1_event(\@f, 'forward', 'DEL');
        next if $ev->{end} <= $ev->{start};
        $n_in++;

        my $matched = find_matching_cluster(\@clusters, $ev, $candidate_num, sub {
            my ($e, $c) = @_;
            return same_interval_event($e, $c, $min_ro, $len_ratio, 0, 0, 0);
        });

        if ($matched >= 0) {
            add_member($clusters[$matched], $ev);
            update_cluster_bounds($clusters[$matched], $ev);
            $n_merged++;
        } else {
            push @clusters, new_cluster($ev);
        }
    }
    close $IN;

    @clusters = sort_clusters(@clusters);
    write_merged_sv($out, \@clusters, 'DEL');
    log_msg("Merged DEL file $file: input=$n_in, merged_into_existing=$n_merged, output=" . scalar(@clusters));
}

sub merge_insertions {
    my ($file, $tol, $candidate_num) = @_;
    my $out = "$file.combined.sorted.txt";
    open(my $IN, '<', $file) or die "Cannot read $file: $!\n";

    my @clusters;
    my ($n_in, $n_merged) = (0, 0);
    while (my $line = <$IN>) {
        next if $line =~ /^\s*#/;
        chomp $line;
        next if $line =~ /^\s*$/;
        my @f = split(/\t/, $line);
        next unless @f >= 17;
        my $ev = parse_head1_event(\@f, 'reciprocal', 'INS');

        # Sequence used for judging whether two insertions are the same event.
        if (defined $f[8] && $f[8] =~ /-/) {
            $ev->{match_seq} = uc revcom($ev->{refseq});
        } else {
            $ev->{match_seq} = uc($ev->{altseq} || '.');
        }
        $ev->{match_seq} = '.' if !defined($ev->{match_seq}) || $ev->{match_seq} eq '';

        $n_in++;
        my $matched = find_matching_cluster(\@clusters, $ev, $candidate_num, sub {
            my ($e, $c) = @_;
            return same_insertion($e, $c, $tol);
        });

        if ($matched >= 0) {
            add_member($clusters[$matched], $ev);
            update_cluster_bounds($clusters[$matched], $ev);
            $n_merged++;
        } else {
            push @clusters, new_cluster($ev);
        }
    }
    close $IN;

    @clusters = sort_clusters(@clusters);
    write_merged_sv($out, \@clusters, 'INS');
    log_msg("Merged INS file $file: input=$n_in, merged_into_existing=$n_merged, output=" . scalar(@clusters));
}

sub merge_head1_interval_sv {
    my %arg = @_;
    my ($file, $out, $svtype, $orientation, $min_ro, $len_ratio, $bp_tol, $candidate_num, $require_subtype) =
        @arg{qw(file out svtype orientation min_ro len_ratio bp_tol candidate_num require_subtype)};

    open(my $IN, '<', $file) or die "Cannot read $file: $!\n";
    my @clusters;
    my ($n_in, $n_merged) = (0, 0);

    while (my $line = <$IN>) {
        next if $line =~ /^\s*#/;
        chomp $line;
        next if $line =~ /^\s*$/;
        my @f = split(/\t/, $line);
        next unless @f >= 17;
        my $ev = parse_head1_event(\@f, $orientation, $svtype);
        $ev->{subtype} = $f[3] || $svtype;
        next if $ev->{end} <= $ev->{start};
        $n_in++;

        my $matched = find_matching_cluster(\@clusters, $ev, $candidate_num, sub {
            my ($e, $c) = @_;
            return same_interval_event($e, $c, $min_ro, $len_ratio, $bp_tol, $require_subtype, 0);
        });

        if ($matched >= 0) {
            add_member($clusters[$matched], $ev);
            update_cluster_bounds($clusters[$matched], $ev);
            $n_merged++;
        } else {
            push @clusters, new_cluster($ev);
        }
    }
    close $IN;

    @clusters = sort_clusters(@clusters);
    write_merged_sv($out, \@clusters, $svtype);
    log_msg("Merged $svtype file $file: input=$n_in, merged_into_existing=$n_merged, output=" . scalar(@clusters));
}

sub merge_translocations {
    my %arg = @_;
    my ($file, $out, $min_ro, $len_ratio, $bp_tol, $candidate_num, $require_qchr) =
        @arg{qw(file out min_ro len_ratio bp_tol candidate_num require_qchr)};

    open(my $IN, '<', $file) or die "Cannot read $file: $!\n";
    my @clusters;
    my ($n_in, $n_merged) = (0, 0);

    while (my $line = <$IN>) {
        next if $line =~ /^\s*#/;
        chomp $line;
        next if $line =~ /^\s*$/;
        my @f = split(/\t/, $line);
        next unless @f >= 11;
        my $ev = parse_trl_event(\@f);
        next if $ev->{end} <= $ev->{start};
        $n_in++;

        my $matched = find_matching_cluster(\@clusters, $ev, $candidate_num, sub {
            my ($e, $c) = @_;
            return same_interval_event($e, $c, $min_ro, $len_ratio, $bp_tol, 1, $require_qchr);
        });

        if ($matched >= 0) {
            add_member($clusters[$matched], $ev);
            update_cluster_bounds($clusters[$matched], $ev);
            $n_merged++;
        } else {
            push @clusters, new_cluster($ev);
        }
    }
    close $IN;

    @clusters = sort_clusters(@clusters);
    write_merged_trl($out, \@clusters);
    log_msg("Merged TRL file $file: input=$n_in, merged_into_existing=$n_merged, output=" . scalar(@clusters));
}

sub parse_head1_event {
    my ($f, $orientation, $svtype) = @_;
    my %ev;
    if ($orientation eq 'reciprocal') {
        # Raw target is non-reference; raw sample is --refname.
        %ev = (
            chr    => $f->[4],
            start  => num($f->[5]),
            end    => num($f->[6]),
            query  => $f->[0],
            qstart => num($f->[1]),
            qend   => num($f->[2]),
            refseq => defined $f->[16] ? $f->[16] : '.',
            altseq => defined $f->[15] ? $f->[15] : '.',
        );
    } else {
        # Raw target is --refname.
        %ev = (
            chr    => $f->[0],
            start  => num($f->[1]),
            end    => num($f->[2]),
            query  => $f->[4],
            qstart => num($f->[5]),
            qend   => num($f->[6]),
            refseq => defined $f->[15] ? $f->[15] : '.',
            altseq => defined $f->[16] ? $f->[16] : '.',
        );
    }
    $ev{svtype} = $svtype;
    $ev{rawtype} = defined $f->[3] ? $f->[3] : $svtype;
    $ev{subtype} = $ev{rawtype};
    $ev{len}    = abs(num($f->[7]));
    $ev{strand} = defined $f->[8]  ? $f->[8]  : '.';
    $ev{five}   = defined $f->[9]  ? $f->[9]  : '.';
    $ev{three}  = defined $f->[10] ? $f->[10] : '.';
    $ev{len}    = abs($ev{end} - $ev{start}) if !$ev{len};
    return \%ev;
}

sub parse_trl_event {
    my ($f) = @_;
    # Raw TRL header:
    # Reference Ref_beg Ref_end Sample Sample_beg Sample_end Strand Ref_len Sample_len TRLtypes Level
    # For reciprocal comparisons, Sample/Sample_beg/Sample_end are standardized as reference coordinates.
    my %ev = (
        chr       => $f->[3],
        start     => num($f->[4]),
        end       => num($f->[5]),
        svtype    => 'TRL',
        rawtype   => defined $f->[9]  ? $f->[9]  : 'TRL',
        subtype   => defined $f->[9]  ? $f->[9]  : 'TRL',
        query     => $f->[0],
        qstart    => num($f->[1]),
        qend      => num($f->[2]),
        strand    => defined $f->[6]  ? $f->[6]  : '.',
        query_len => abs(num($f->[7])),
        len       => abs(num($f->[8])),
        trltype   => defined $f->[9]  ? $f->[9]  : '.',
        level     => defined $f->[10] ? $f->[10] : '.',
        five      => '.',
        three     => '.',
        refseq    => '.',
        altseq    => '.',
    );
    $ev{len} = abs($ev{end} - $ev{start}) if !$ev{len};
    return \%ev;
}

sub find_matching_cluster {
    my ($clusters, $ev, $candidate_num, $callback) = @_;
    my $checked = 0;
    for (my $i = $#$clusters; $i >= 0; $i--) {
        next unless $clusters->[$i]{chr} eq $ev->{chr};
        $checked++;
        return $i if $callback->($ev, $clusters->[$i]);
        last if $checked >= $candidate_num;
    }
    return -1;
}

sub new_cluster {
    my ($ev) = @_;
    my %cl = %$ev;
    $cl{members} = [];
    $cl{member_seen} = {};
    $cl{min_start} = $ev->{start};
    $cl{max_end} = $ev->{end};
    add_member(\%cl, $ev);
    return \%cl;
}

sub add_member {
    my ($cl, $ev) = @_;
    my $m = join('_', $ev->{query}, $ev->{qstart}, $ev->{qend}, $ev->{len});
    return if $cl->{member_seen}{$m}++;
    push @{$cl->{members}}, $m;
}

sub update_cluster_bounds {
    my ($cl, $ev) = @_;
    $cl->{min_start} = defined $cl->{min_start} ? min2($cl->{min_start}, $ev->{start}) : $ev->{start};
    $cl->{max_end}   = defined $cl->{max_end}   ? max2($cl->{max_end},   $ev->{end})   : $ev->{end};
    $cl->{support_len_sum} = ($cl->{support_len_sum} || $cl->{len}) + $ev->{len};
}

sub same_interval_event {
    my ($ev, $cl, $min_ro, $len_ratio, $bp_tol, $require_subtype, $require_qchr) = @_;
    return 0 unless $ev->{chr} eq $cl->{chr};
    if ($require_subtype) {
        return 0 unless ($ev->{subtype} || '') eq ($cl->{subtype} || '');
    }
    if ($require_qchr) {
        return 0 unless ($ev->{query} || '') eq ($cl->{query} || '');
    }

    my $len1 = max2(1, $ev->{end} - $ev->{start});
    my $len2 = max2(1, $cl->{end} - $cl->{start});
    my $lr = $ev->{len} >= $cl->{len} ? $ev->{len} / max2(1, $cl->{len}) : $cl->{len} / max2(1, $ev->{len});
    return 0 if defined($len_ratio) && $len_ratio >= 0 && $lr > (1 + $len_ratio);

    my $ol = interval_overlap($ev->{start}, $ev->{end}, $cl->{start}, $cl->{end});
    if ($ol > 0) {
        my $ro1 = $ol / $len1;
        my $ro2 = $ol / $len2;
        return 1 if $ro1 >= $min_ro && $ro2 >= $min_ro;
    }

    # For fragmented chain/net calls, nearby breakpoints may be a better criterion
    # than exact reciprocal overlap.
    if (defined($bp_tol) && $bp_tol > 0) {
        return 1 if abs($ev->{start} - $cl->{start}) <= $bp_tol && abs($ev->{end} - $cl->{end}) <= $bp_tol;
    }
    return 0;
}

sub same_insertion {
    my ($ev, $cl, $tol) = @_;
    return 0 unless $ev->{chr} eq $cl->{chr};
    return 0 if abs($ev->{start} - $cl->{start}) > $tol;

    my $seq1 = $ev->{match_seq};
    my $seq2 = $cl->{match_seq};
    if (is_real_seq($seq1) && is_real_seq($seq2) && $seq1 eq $seq2) {
        return 1;
    }

    if (defined $ev->{five} && defined $cl->{five} && $ev->{five} eq $cl->{five}) {
        return 1;
    }
    if (defined $ev->{three} && defined $cl->{three} && $ev->{three} eq $cl->{three}) {
        return 1;
    }

    my $len1 = max2(1, $ev->{len});
    my $len2 = max2(1, $cl->{len});
    my $ratio = $len1 >= $len2 ? $len1 / $len2 : $len2 / $len1;
    return 0 if $ratio > 1.10;

    if (is_real_seq($seq1) && is_real_seq($seq2)) {
        if ($len1 > 5 && $len1 < 50 && kmer_similarity($seq1, $seq2, 4) > 0.50) {
            return 1;
        }
        if ($len1 >= 50 && kmer_similarity($seq1, $seq2, 10) > 0.50) {
            return 1;
        }
    }
    return 0;
}

sub write_merged_sv {
    my ($out, $clusters, $svtype) = @_;
    open(my $OUT, '>', $out) or die "Cannot write $out: $!\n";
    print $OUT join("\t", ("#CHROM", qw(POS END ID SVTYPE SVLEN MERGE_SAMPLES_NUM MERGE_SAMPLES QUERY Q_POS Q_END FIVE THREE REFseq ALTseq))), "\n";
    for my $cl (@$clusters) {
        my @members = @{$cl->{members} || []};
        next unless @members;
        my $id = $members[0];
        my $num = scalar @members;
        my $merge_samples = join(',', @members);
        print $OUT join("\t",
            $cl->{chr}, $cl->{start}, $cl->{end}, $id, $svtype, $cl->{len},
            $num, $merge_samples,
            $cl->{query}, $cl->{qstart}, $cl->{qend},
            $cl->{five}, $cl->{three}, $cl->{refseq}, $cl->{altseq}
        ), "\n";
    }
    close $OUT;
}

sub write_merged_trl {
    my ($out, $clusters) = @_;
    open(my $OUT, '>', $out) or die "Cannot write $out: $!\n";
    print $OUT join("\t", ("#CHROM", qw(POS END ID SVTYPE SVLEN MERGE_SAMPLES_NUM MERGE_SAMPLES QUERY Q_POS Q_END STRAND REF_LEN QUERY_LEN TRLTYPE LEVEL))), "\n";
    for my $cl (@$clusters) {
        my @members = @{$cl->{members} || []};
        next unless @members;
        my $id = $members[0];
        print $OUT join("\t",
            $cl->{chr}, $cl->{start}, $cl->{end}, $id, 'TRL', $cl->{len},
            scalar(@members), join(',', @members),
            $cl->{query}, $cl->{qstart}, $cl->{qend}, $cl->{strand},
            $cl->{len}, $cl->{query_len}, $cl->{trltype}, $cl->{level}
        ), "\n";
    }
    close $OUT;
}

sub sort_clusters {
    return sort { $a->{chr} cmp $b->{chr} || $a->{start} <=> $b->{start} || $a->{end} <=> $b->{end} } @_;
}

sub kmer_similarity {
    my ($s1, $s2, $k) = @_;
    return 0 unless is_real_seq($s1) && is_real_seq($s2);
    return 0 if length($s1) < $k || length($s2) < $k;

    my ($short, $long) = length($s1) <= length($s2) ? ($s1, $s2) : ($s2, $s1);
    my %long_kmer;
    for (my $i = 0; $i <= length($long) - $k; $i++) {
        $long_kmer{substr($long, $i, $k)} = 1;
    }

    my ($hit, $total) = (0, 0);
    for (my $i = 0; $i <= length($short) - $k; $i++) {
        my $seed = substr($short, $i, $k);
        $total++;
        $hit++ if exists $long_kmer{$seed};
    }
    return $total ? $hit / $total : 0;
}

sub interval_overlap {
    my ($s1, $e1, $s2, $e2) = @_;
    my $s = max2($s1, $s2);
    my $e = min2($e1, $e2);
    return $e > $s ? $e - $s : 0;
}

sub is_real_seq {
    my ($s) = @_;
    return 0 unless defined $s;
    return 0 if $s eq '' || $s eq '.';
    return 0 if $s =~ /^N+$/i;
    return 1;
}

sub revcom {
    my ($seq) = @_;
    return '.' unless defined $seq;
    $seq = reverse $seq;
    $seq =~ tr/ACGTNacgtn/TGCANtgcan/;
    return $seq;
}

sub num {
    my ($x) = @_;
    return 0 unless defined $x && $x ne '';
    $x =~ s/,//g;
    return $x + 0;
}

sub min2 { $_[0] < $_[1] ? $_[0] : $_[1] }
sub max2 { $_[0] > $_[1] ? $_[0] : $_[1] }
